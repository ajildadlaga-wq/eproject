/**
 * One use case description in the layout the requirements-analysis course
 * uses: goal, category, pre/post conditions, actor, trigger, then the main,
 * extension and alternative flows.
 */
function useCase(uc) {
  return TBL({
    caption: `${uc.id} — ${uc.name}.`,
    size: 19,
    head: ['Ажлын явц', uc.name],
    widths: [26, 74],
    firstColBold: true,
    rows: [
      ['Дугаар', uc.id],
      ['Зорилго', uc.goal],
      ['Ангилал', uc.category],
      ['Тоглогч (Actor)', uc.actor],
      ['Угтвар нөхцөл', uc.pre],
      ['Дараах нөхцөл (амжилттай)', uc.postOk],
      ['Дараах нөхцөл (бүтэлгүйтэл)', uc.postFail],
      ['Өдөөгч үзэгдэл', uc.trigger],
      ['Тайлбарлалт (Main Flow)', uc.main.join('\n')],
      ['Өргөтгөл (Extension)', uc.ext.join('\n')],
      ['Хувилбар (Alternative Flow)', uc.alt.join('\n')],
      ['Холбогдох шаардлага', uc.frs],
    ],
  });
}

